// ── Investigation history from localStorage ──────────────────────────────────
interface InvestigationRecord {
  id: string;
  timestamp: string;
  query: string;
  type: 'entity' | 'graph' | 'prediction' | 'anomaly';
  result: string;
}

function getHistory(): InvestigationRecord[] {
  try {
    return JSON.parse(localStorage.getItem('dhapnet_investigations') || '[]');
  } catch {
    return [];
  }
}

function clearHistory() {
  localStorage.removeItem('dhapnet_investigations');
}

// ── CSV download helper ──────────────────────────────────────────────────────
function downloadCSV(data: Record<string, unknown>[], filename: string) {
  if (data.length === 0) return;
  const headers = Object.keys(data[0]);
  const rows = data.map(row => headers.map(h => JSON.stringify(row[h] ?? '')).join(','));
  const csv = [headers.join(','), ...rows].join('\n');
  const blob = new Blob([csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

